# Make-Cert.ps1
# ---------------------------------------------------------------------------
# Create a self-signed code-signing certificate (run once on the source machine).
#
# Produces:
#   LGGZ-CodeSign.cer        - public certificate, copy to other machines to trust
#   LGGZ-CodeSign.pfx        - private key, used to sign (keep it safe)
#   cert-info.txt            - thumbprint and related info, read by the other scripts
#
# Note: a self-signed certificate removes "Unknown publisher", but NOT the
#       SmartScreen "Windows protected your PC" warning - that needs a CA-issued certificate.
#       See README.md in this folder.
# ---------------------------------------------------------------------------

[CmdletBinding()]
param(
    # Certificate name: what UAC / file properties show as the publisher
    [string]$Subject = "CN=LGGZ",

    # Password for the exported .pfx (default 123456; it only prevents accidents, it is not strong)
    [string]$PfxPassword = "123456",

    # Validity in years
    [int]$Years = 10,

    # Also install it into CurrentUser -> Trusted Root Certification Authorities so this machine trusts it
    [switch]$TrustLocal
)

$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path

Write-Host "=== 1/3 create a self-signed code-signing certificate ===" -ForegroundColor Cyan
Write-Host "  subject: $Subject"
Write-Host "  validity: $Years year(s)"

# 1.3.6.1.5.5.7.3.3 = Code Signing enhanced key usage
$cert = New-SelfSignedCertificate `
    -Type CodeSigningCert `
    -Subject $Subject `
    -KeyUsage DigitalSignature `
    -KeyExportPolicy Exportable `
    -KeyLength 2048 `
    -HashAlgorithm SHA256 `
    -NotAfter (Get-Date).AddYears($Years) `
    -CertStoreLocation 'Cert:\CurrentUser\My' `
    -TextExtension @('2.5.29.37={text}1.3.6.1.5.5.7.3.3')

Write-Host "  thumbprint: $($cert.Thumbprint)" -ForegroundColor Green

# ---------- export the .cer (public key) ----------
$cerPath = Join-Path $here 'LGGZ-CodeSign.cer'
Export-Certificate -Cert $cert -FilePath $cerPath -Type CERT -Force | Out-Null
Write-Host "=== 2/3 public certificate exported ===" -ForegroundColor Cyan
Write-Host "  $cerPath"

# ---------- export the .pfx (with private key) ----------
$pfxPath = Join-Path $here 'LGGZ-CodeSign.pfx'
$pfxPwd = ConvertTo-SecureString -String $PfxPassword -AsPlainText -Force
Export-PfxCertificate -Cert $cert -FilePath $pfxPath -Password $pfxPwd -Force | Out-Null
Write-Host "  $pfxPath  (**never share**: anyone holding it can sign as you)" -ForegroundColor Yellow

# ---------- record info ----------
$infoPath = Join-Path $here 'cert-info.txt'
@(
    "# generated by Make-Cert.ps1; Sign-App.ps1 / Install-Trust.ps1 read this file"
    "Thumbprint=$($cert.Thumbprint)"
    "Subject=$($cert.Subject)"
    "NotAfter=$($cert.NotAfter.ToString('yyyy-MM-dd'))"
    "PfxPassword=$PfxPassword"
) | Set-Content -Path $infoPath -Encoding UTF8
Write-Host "=== 3/3 certificate info recorded ===" -ForegroundColor Cyan
Write-Host "  $infoPath"

if ($TrustLocal) {
    Write-Host ""
    Write-Host "=== install the certificate into CurrentUser\Root (trust it locally) ===" -ForegroundColor Cyan
    Import-Certificate -FilePath $cerPath -CertStoreLocation 'Cert:\CurrentUser\Root' | Out-Null
    Write-Host "  imported into Cert:\CurrentUser\Root" -ForegroundColor Green
}

Write-Host ""
Write-Host "Next:" -ForegroundColor Green
Write-Host "  1) sign the binaries:  powershell -ExecutionPolicy Bypass -File .\Sign-App.ps1"
Write-Host "  2) on another machine, run this there [as administrator]:"
Write-Host "     powershell -ExecutionPolicy Bypass -File .\Install-Trust.ps1"
